export function Icon({
  name,
  size = 18,
  className = "",
}: {
  name: IconName
  size?: number
  className?: string
}) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.8"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {paths[name] ?? paths.wallet}
    </svg>
  )
}

export const ugx = (amount: number): string => {
  const abs = Math.abs(Math.round(amount))
  return `${amount < 0 ? "− " : ""}UGX ${abs.toLocaleString("en-UG")}`
}

export const ugxAbs = (amount: number): string =>
  `UGX ${Math.abs(Math.round(amount)).toLocaleString("en-UG")}`

export function safeIconName(candidate: string | null | undefined): IconName {
  if (!candidate) return "wallet"
  return candidate in paths ? (candidate as IconName) : "wallet"
}

